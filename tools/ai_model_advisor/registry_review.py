"""Create a stable, reviewable summary of unregistered model-source signals.

This never changes the model registry. A new signal is a review request,
not evidence that a new model is generally available.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ISSUE_TITLE = "Model registry: review unregistered source signals"


def review_signals(report: dict[str, Any]) -> list[str]:
    if not isinstance(report, dict):
        raise ValueError("scan report must be a JSON object")
    raw = report.get("new_unknown_signals", [])
    if not isinstance(raw, list):
        raise ValueError("new_unknown_signals must be an array")
    if any(not isinstance(value, str) for value in raw):
        raise ValueError("new_unknown_signals must contain strings")
    # Escape Markdown-like source text to avoid injecting links or markup
    # from an untrusted remote model-source page into an issue body.
    result: set[str] = set()
    for value in raw:
        normalized = " ".join(value.split()).strip()
        if not normalized:
            continue
        if len(normalized) > 120:
            normalized = normalized[:120] + "..."
        normalized = (
            normalized.replace("\\", "\\\\").replace("[", "\\[")
            .replace("]", "\\]").replace("<", "&lt;").replace(">", "&gt;")
            .replace("*", "\\*").replace("_", "\\_")
        )
        result.add(normalized)
    return sorted(result, key=str.casefold)


def issue_body(signals: list[str]) -> str:
    if not signals:
        raise ValueError("Cannot create a review issue without signals")
    items = "\n".join(f"- {signal}" for signal in signals)
    return (
        "## Unverified model-source signals\n\n"
        "The scheduled source scan found model-like labels absent from its "
        "comparison baseline. **These are not confirmed model releases.** "
        "Review official model IDs, availability, capabilities, pricing, "
        "and source evidence before updating the registry.\n\n"
        f"{items}\n\n"
        "### Review checklist\n\n"
        "- [ ] Confirm the identity and official source of every signal\n"
        "- [ ] Distinguish historical labels/aliases from real new releases\n"
        "- [ ] Update registry and source baseline only after verification\n"
        "- [ ] Run CI and the source-scan tests\n"
        "- [ ] Close this issue after review; do not auto-promote models\n\n"
        "Source scan summaries and downloadable artifacts: "
        "[Model Registry Monitor](../actions/workflows/model-registry-monitor.yml).\n"
        "\n"
        "_Generated by a scheduled monitor; a human must approve changes._\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Prepare human review of source scan signals")
    parser.add_argument("--report", required=True, type=Path)
    parser.add_argument("--body", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args(argv)
    report = json.loads(args.report.read_text(encoding="utf-8"))
    signals = review_signals(report)
    args.body.parent.mkdir(parents=True, exist_ok=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.body.write_text(issue_body(signals) if signals else "", encoding="utf-8")
    args.output.write_text(
        json.dumps({"review_required": bool(signals), "signals": signals}, indent=2) + "\n",
        encoding="utf-8",
    )
    if signals:
        print(f"Review required for {len(signals)} unverified model-source signal(s).")
    else:
        print("No new source signals. Registry unchanged.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
